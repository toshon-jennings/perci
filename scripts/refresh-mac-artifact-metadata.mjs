import { createHash } from 'node:crypto';
import { readFileSync, statSync, writeFileSync } from 'node:fs';
import { basename, dirname, resolve } from 'node:path';
import { createRequire } from 'node:module';
import yaml from 'js-yaml';
const require = createRequire(import.meta.url);
const { executeAppBuilderAsJson } = require('app-builder-lib/out/util/appBuilder.js');
const image = resolve(process.argv[2] || '');
if (!image.endsWith('.dmg')) throw new Error('Expected a repaired DMG path.');
await executeAppBuilderAsJson(['blockmap', '--input', image, '--output', `${image}.blockmap`]);
const manifestPath = resolve(dirname(image), 'latest-mac.yml');
const manifest = yaml.load(readFileSync(manifestPath, 'utf8'));
const entry = manifest.files?.find(file => file.url === basename(image));
if (!entry) throw new Error('Repaired DMG is absent from the update manifest.');
entry.sha512 = createHash('sha512').update(readFileSync(image)).digest('base64');
entry.size = statSync(image).size;
if (manifest.path === entry.url) manifest.sha512 = entry.sha512;
writeFileSync(manifestPath, yaml.dump(manifest));
console.log(`Refreshed metadata for ${basename(image)}.`);
